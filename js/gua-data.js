const SIXTY_FOUR_GUA = Object.fromEntries(GUA_SEED.map(([code, order, name, dec, advice]) => {
    const upper = TRIGRAMS[code.slice(0, 3)];
    const lower = TRIGRAMS[code.slice(3, 6)];
    return [code, {
        code,
        order,
        name,
        dec,
        advice,
        upper,
        lower,
        symbol: `${upper?.symbol || ""}${lower?.symbol || ""}`,
        yao: buildYaoText(name)
    }];
}));

